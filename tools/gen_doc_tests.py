#!/usr/bin/env python3
"""Extract executable assertions from @code{.test} blocks into a test file.

A block looks like this:

    /// @code{.test}
    /// @setup Config cfg; cfg.workdir = "."; cfg.normalize();
    /// expression   ==>   expected
    /// @endcode

Every `expr ==> expected` line becomes CHECK(expr == expected). @setup lines are
emitted verbatim, in order, before the assertions of that block. Plain @code
blocks are left alone — they render in the docs and are not compiled.

The point is not to save writing tests. It is that a documented example which
is never executed rots silently: the code changes, the tests go red, and the
comment quietly becomes a lie.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = sorted(list((ROOT / "src").rglob("*.cpp")) + list((ROOT / "include").rglob("*.hpp")))
OUT = ROOT / "tests" / "test_docs.cpp"


def strip_comment(line):
    """`    /// foo` -> `foo`; None when the line is not a /// comment."""
    m = re.match(r"^\s*///\s?(.*)$", line)
    return m.group(1).rstrip() if m else None


def extract(path):
    """Yield (line_no, [(kind, payload, line_no)]) per test block.

    Statements and assertions stay in source order. Collecting all the @setup
    lines first would break any example whose point is that something changes
    between two assertions — remember_allow's counter is exactly that.
    """
    lines = path.read_text().split("\n")
    i = 0
    while i < len(lines):
        body = strip_comment(lines[i])
        if body is None or not body.startswith("@code{.test}"):
            i += 1
            continue
        start = i + 1
        steps = []
        i += 1
        while i < len(lines):
            body = strip_comment(lines[i])
            if body is None or body.startswith("@endcode"):
                break
            if body.startswith("@setup "):
                steps.append(("stmt", body[len("@setup "):], i + 1))
            elif "==>" in body:
                expr, expected = body.split("==>", 1)
                steps.append(("check", (expr.strip(), expected.strip()), i + 1))
            elif body.strip():
                steps.append(("stmt", body, i + 1))
            i += 1
        if any(k == "check" for k, _, _ in steps):
            yield start, steps
        i += 1


def main():
    blocks = []
    for path in SOURCES:
        rel = path.relative_to(ROOT)
        for start, steps in extract(path):
            blocks.append((rel, start, steps))

    out = ['// GENERATED by tools/gen_doc_tests.py — do not edit.',
           '//',
           '// Assertions lifted out of @code{.test} blocks in the headers and sources.',
           '// Regenerate with:  python3 tools/gen_doc_tests.py',
           '',
           '#include "microtest.hpp"',
           '#include "doc_prelude.hpp"',
           '',
           'using namespace mini;',
           '']

    for rel, start, steps in blocks:
        name = "doc_" + re.sub(r"\W", "_", str(rel)) + f"_L{start}"
        out.append(f"/// From {rel}:{start}")
        out.append(f"TEST({name}) {{")
        for kind, payload, ln in steps:          # source order preserved
            if kind == "stmt":
                out.append(f"    {payload}")
            else:
                expr, expected = payload
                msg = f"{rel}:{ln} 的示例失效了"
                out.append(f'    CHECK_MSG(({expr}) == ({expected}), "{msg}");')
        out.append("}")
        out.append("")

    out.append("int main() { return mt::run_all(); }")
    OUT.write_text("\n".join(out))

    n_checks = sum(sum(1 for k, _, _ in st if k == "check") for _, _, st in blocks)
    print(f"{OUT.relative_to(ROOT)}: {len(blocks)} 个块, {n_checks} 条断言")
    for rel, start, steps in blocks:
        n = sum(1 for k, _, _ in steps if k == "check")
        print(f"  {rel}:{start}  ({n} 条)")
    return 0 if blocks else 1


if __name__ == "__main__":
    sys.exit(main())
